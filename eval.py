#!/usr/bin/env python3
"""
PlanBench unified evaluation (judge) script.
Scores model answers generated by inference.py.

For planbench-v (vision): uses critical_points + image to judge answers.
For planbench (text): uses reference answer to judge answers.

Backend: OpenRouter (shared with inference.py).

Usage:
  # Score vision answers
  python eval.py --judge openai/gpt-4o-mini \
      --input results/gemini-2.5-pro.json \
      --image-dir planbench-v/images --output results/gemini-2.5-pro-scored.json

  # Score text answers
  python eval.py --judge openai/gpt-4o-mini \
      --input results/gpt-4o-mini-text.json \
      --output results/gpt-4o-mini-text-scored.json
"""

import argparse
import json
import os
import re
from concurrent.futures import ThreadPoolExecutor, as_completed
from typing import Dict, List

from tqdm import tqdm

from inference import get_backend


EVAL_PROMPT_VISION = """请根据问题、得分点列表和图像内容，对下面的回答进行评分。

问题：{question}

得分点列表：
{critical_points}

待评估回答：{answer}

评分标准：
请逐一检查模型回答是否涉及到每个得分点：
- 对于每个得分点，如果模型回答中有涉及到相关内容，请给1分
- 如果模型回答中没有涉及到或描述错误，请给0分
- 得分点之间是互斥的，每个得分点最多得1分

请按以下格式进行评分：
1. 得分点1：[0/1] - 简要说明是否包含该得分点及依据
2. 得分点2：[0/1] - 简要说明是否包含该得分点及依据
...

最终得分：X/Y（X为累计得分，Y为总分，即得分点总数）
"""

EVAL_PROMPT_TEXT = """你是一位城市规划考试阅卷专家。请根据参考答案对以下回答进行评分。

问题：{question}

参考答案：{reference}

待评估回答：{answer}

评分标准（满分2分）：
- 解析Score（0-1分）：回答的分析逻辑是否正确、完整
- 回答Score（0-1分）：最终答案是否正确

请按以下格式评分：
解析Score：[0/0.5/1] - 简要说明
回答Score：[0/0.5/1] - 简要说明

最终得分：X/2
"""


def parse_score_vision(score_text: str) -> float:
    """Parse vision eval score: X/Y -> normalized to 2-point scale."""
    m = re.search(r"最终得分：\s*(\d+(?:\.\d+)?)/(\d+(?:\.\d+)?)", score_text)
    if m:
        score, total = float(m.group(1)), float(m.group(2))
        return (score / total) * 2 if total > 0 else 0.0
    return 0.0


def parse_score_text(score_text: str) -> float:
    """Parse text eval score: X/2."""
    m = re.search(r"最终得分：\s*(\d+(?:\.\d+)?)/2", score_text)
    if m:
        return float(m.group(1))
    return 0.0


def eval_item_vision(backend, item: Dict, image_dir: str) -> Dict:
    question = item.get("question", "")
    critical_points = item.get("critical_points", [])
    answer = item.get("summary", "") or item.get("raw_response", "")
    thinking = item.get("thinking", "")
    if thinking:
        answer = thinking + "\n" + answer

    image_path = None
    if item.get("image_url"):
        image_path = os.path.join(image_dir, os.path.basename(item["image_url"]))
        if not os.path.exists(image_path):
            image_path = os.path.join(image_dir, item["image_url"])
        if not os.path.exists(image_path):
            image_path = None

    prompt = EVAL_PROMPT_VISION.format(
        question=question,
        critical_points="\n".join(critical_points),
        answer=answer,
    )
    score_text = backend.call(prompt, image_path)
    score = parse_score_vision(score_text)

    result = item.copy()
    result["score"] = score
    result["score_text"] = score_text
    return result


def eval_item_text(backend, item: Dict) -> Dict:
    question = item.get("instruction", "")
    reference = item.get("response", "")
    answer = item.get("summary", "") or item.get("raw_response", "")

    prompt = EVAL_PROMPT_TEXT.format(
        question=question, reference=reference, answer=answer
    )
    score_text = backend.call(prompt)
    score = parse_score_text(score_text)

    result = item.copy()
    result["score"] = score
    result["score_text"] = score_text
    return result


def print_summary(results: List[Dict], label: str) -> float:
    type_scores: Dict[str, List[float]] = {}
    for r in results:
        t = r.get("type", "unknown")
        type_scores.setdefault(t, []).append(r.get("score", 0))

    print(f"\n===== {label} =====")
    all_scores = []
    for t, scores in sorted(type_scores.items()):
        avg = sum(scores) / len(scores)
        print(f"  {t}: {avg:.3f}/2 (n={len(scores)})")
        all_scores.extend(scores)
    if all_scores:
        overall = sum(all_scores) / len(all_scores)
        print(f"  >> Overall: {overall:.3f}/2 ({overall/2*100:.1f}%), n={len(all_scores)}")
        return overall
    return 0.0


def main():
    parser = argparse.ArgumentParser(description="PlanBench unified evaluation")
    parser.add_argument("--judge", required=True, help="Judge model name")
    parser.add_argument("--input", required=True, help="Inference output JSON")
    parser.add_argument("--image-dir", default="planbench-v/images")
    parser.add_argument("--output", required=True, help="Scored output JSON")
    parser.add_argument("--max-workers", type=int, default=1)
    args = parser.parse_args()

    with open(args.input, "r", encoding="utf-8") as f:
        data = json.load(f)

    is_vision = any(item.get("image_url") or item.get("critical_points") for item in data)
    print(f"Input: {len(data)} items, mode={'vision' if is_vision else 'text'}")

    backend = get_backend(args.judge)
    print(f"Judge: {args.judge}")

    os.makedirs(os.path.dirname(args.output) or ".", exist_ok=True)
    results = []

    if args.max_workers <= 1:
        for i, item in enumerate(data):
            if is_vision:
                result = eval_item_vision(backend, item, args.image_dir)
            else:
                result = eval_item_text(backend, item)
            results.append(result)
            if (i + 1) % 10 == 0:
                avg = sum(r["score"] for r in results) / len(results)
                print(f"  [{i+1}/{len(data)}] running avg: {avg:.3f}/2")
                with open(args.output, "w", encoding="utf-8") as f:
                    json.dump(results, f, ensure_ascii=False, indent=2)
    else:
        def _eval(item):
            if is_vision:
                return eval_item_vision(backend, item, args.image_dir)
            return eval_item_text(backend, item)

        with ThreadPoolExecutor(max_workers=args.max_workers) as executor:
            futures = {executor.submit(_eval, item): i for i, item in enumerate(data)}
            for future in tqdm(as_completed(futures), total=len(futures)):
                results.append(future.result())

    with open(args.output, "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)

    print_summary(results, f"Judge={args.judge}")
    print(f"\nSaved {len(results)} scored results to {args.output}")


if __name__ == "__main__":
    main()
